
import { timingSafeEqual } from "node:crypto";
import { NextResponse } from "next/server";
import { Resend } from "resend";
import {
  getMetaInsightsReport,
  MetaMonitoringError,
} from "@/lib/meta-monitoring";

export async function GET(request: Request) {
  const cronSecret = process.env.CRON_SECRET;
  const expectedAuthorization = cronSecret ? `Bearer ${cronSecret}` : "";
  const providedAuthorization = request.headers.get("authorization") ?? "";
  const expected = Buffer.from(expectedAuthorization);
  const provided = Buffer.from(providedAuthorization);

  if (
    !cronSecret ||
    expected.length !== provided.length ||
    !timingSafeEqual(expected, provided)
  ) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  try {
    const report = await getMetaInsightsReport();

    let emailSent = false;

    if (report.alerts.length > 0) {
      const apiKey = process.env.RESEND_API_KEY;

      if (!apiKey) {
        return NextResponse.json(
          { ok: false, error: "RESEND_API_KEY is not configured." },
          { status: 500 }
        );
      }

      const resend = new Resend(apiKey);

      const alertLines = report.alerts.map((alert) => {
        const metricNames = {
          spend: "Ad spend",
          ctr: "CTR",
          cpc: "CPC",
        };

        const actual = alert.metric === "ctr"
          ? `${alert.actual}%`
          : `$${alert.actual.toFixed(2)}`;

        const threshold = alert.metric === "ctr"
          ? `${alert.threshold}%`
          : `$${alert.threshold.toFixed(2)}`;

        return `${metricNames[alert.metric]} is ${alert.direction} threshold. Actual: ${actual}; threshold: ${threshold}.`;
      });

      const { error } = await resend.emails.send({
        from: "VAULT 13 Ads Monitor <onboarding@resend.dev>",
        to: ["sanjmunkhochir1234@gmail.com"],
        subject: `VAULT 13 Meta Ads Alert: ${report.alerts.length} alert(s)`,
        text: [
          "VAULT 13 Meta Ads Monitoring Alert",
          "",
          ...alertLines,
          "",
          "This alert was generated by the scheduled Meta Ads monitor.",
        ].join("\n"),
      });

      if (error) {
        console.error("Resend email error:", error);
        return NextResponse.json(
          { ok: false, error: "Failed to send alert email." },
          { status: 502 }
        );
      }

      emailSent = true;
    }

    return NextResponse.json({
      ok: true,
      checkedAt: new Date().toISOString(),
      emailSent,
      ...report,
    });
  } catch (error) {
    if (error instanceof MetaMonitoringError) {
      return NextResponse.json(
        { ok: false, error: error.message },
        { status: error.status }
      );
    }

    console.error("Meta monitoring error:", error);

    return NextResponse.json(
      { ok: false, error: "Meta monitoring request failed." },
      { status: 502 }
    );
  }
}
